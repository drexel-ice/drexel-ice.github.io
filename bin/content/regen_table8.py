#!/usr/bin/env python3
"""Regenerate _data/table8.yml from the editable Markdown source at
content/table8.md.

The Markdown file is the sole source of truth for the EDA-Schema-V2
Table 8 benchmark dataset. Non-coders edit the markdown; this script
parses it and writes the YAML that Jekyll consumes via
_includes/table8.html.

Triggered by .github/workflows/regen-table8.yml on push to main when
content/table8.md changes; can also be run locally:

    python3 bin/content/regen_table8.py            # write _data/table8.yml
    python3 bin/content/regen_table8.py --check    # validate only, no write
    python3 bin/content/regen_table8.py --output /tmp/x.yml

Output is byte-identical to the legacy scripts/gen_table8.py emitter so
the migration commit shows zero data diff.
"""
from __future__ import annotations

import argparse
import csv
import io
import os
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
MD_PATH = ROOT / "content" / "table8.md"
YML_PATH = ROOT / "_data" / "table8.yml"

HEADER_COMMENT = (
    "# Auto-generated by bin/content/regen_table8.py from content/table8.md - do not edit by hand.\n"
    "# Source: EDA-Schema-V2, Table 8 (arXiv:2605.06952v1).\n"
)

EXPECTED_HEADER_ROW1 = [
    "stage", "-",
    "FP", "FP", "FP", "FP",
    "GP", "GP", "GP", "GP",
    "DP", "DP", "DP", "DP",
    "CTS", "CTS", "CTS", "CTS",
    "GR", "GR", "GR", "GR",
]
STAGE_LABELS = ["FP/NG45", "FP/SKY130", "FP/IHP130", "FP/ASAP7",
                "GP/NG45", "GP/SKY130", "GP/IHP130", "GP/ASAP7",
                "DP/NG45", "DP/SKY130", "DP/IHP130", "DP/ASAP7",
                "CTS/NG45", "CTS/SKY130", "CTS/IHP130", "CTS/ASAP7",
                "GR/NG45", "GR/SKY130", "GR/IHP130", "GR/ASAP7"]

SENTINEL = "-"


class ParseError(Exception):
    pass


def split_frontmatter(text: str) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise ParseError(
            "content/table8.md: missing YAML frontmatter. The file must "
            "start with '---' on its own line, then YAML, then '---'."
        )
    meta = yaml.safe_load(m.group(1)) or {}
    body = m.group(2)
    for key in ("caption", "pdks", "groups", "fp_note", "gr_note"):
        if key not in meta:
            raise ParseError(
                f"content/table8.md frontmatter: missing required key '{key}'."
            )
    if list(meta["pdks"]) != ["NG45", "SKY130", "IHP130", "ASAP7"]:
        raise ParseError(
            "content/table8.md frontmatter: pdks must be exactly "
            "[NG45, SKY130, IHP130, ASAP7] in that order."
        )
    if len(meta["groups"]) != 5:
        raise ParseError(
            f"content/table8.md frontmatter: expected 5 groups, "
            f"got {len(meta['groups'])}."
        )
    return meta, body


BLOCK_RE = re.compile(
    r"^##\s+(?P<metric>.+?)\s+\((?P<unit>.+?)\)\s*\n"
    r"(?:.*?\n)*?"
    r"```tsv\n(?P<tsv>.*?)\n```",
    re.M | re.S,
)


def parse_blocks(body: str) -> list[dict]:
    blocks = []
    matches = list(BLOCK_RE.finditer(body))
    if not matches:
        raise ParseError(
            "content/table8.md: no '## <metric> (<unit>)' blocks with "
            "```tsv code fences found in the body."
        )
    for m in matches:
        metric = m.group("metric").strip()
        unit = m.group("unit").strip()
        tsv = m.group("tsv")
        rows = parse_tsv_block(metric, unit, tsv)
        fp = derive_and_validate_fp(metric, rows)
        validate_gr_pairing(metric, rows)
        blocks.append({"metric": metric, "unit": unit, "fp": fp, "rows": rows})
    return blocks


def parse_tsv_block(metric: str, unit: str, tsv: str) -> list[dict]:
    reader = list(csv.reader(io.StringIO(tsv), delimiter="\t"))
    if len(reader) < 3:
        raise ParseError(
            f'block "{metric} ({unit})": TSV must have 2 header rows '
            f"and at least 1 data row; got {len(reader)} lines."
        )
    hdr1, hdr2, *data = reader
    if hdr1 != EXPECTED_HEADER_ROW1:
        raise ParseError(
            f'block "{metric} ({unit})": header row 1 must be exactly:\n'
            f"  {chr(9).join(EXPECTED_HEADER_ROW1)}\n"
            f"got:\n  {chr(9).join(hdr1)}"
        )
    if len(hdr2) != 22 or hdr2[0] != "sub" or hdr2[1] != "type":
        raise ParseError(
            f'block "{metric} ({unit})": header row 2 must start with '
            f'"sub<TAB>type" and have 22 columns total; got {len(hdr2)} '
            f"columns starting with {hdr2[:2]!r}."
        )
    rows = []
    for raw in data:
        if not raw or all(c == "" for c in raw):
            continue
        if len(raw) != 22:
            raise ParseError(
                f'block "{metric} ({unit})" row {raw[0]!r}: expected 22 '
                f"columns (sub + type + 20 values), got {len(raw)}."
            )
        sub = raw[0].strip()
        rtype = raw[1].strip()
        v = [c.strip() for c in raw[2:]]
        validate_row(metric, unit, sub, rtype, v)
        cleaned = [c for c in v if c != SENTINEL]
        rows.append({"sub": sub, "type": rtype, "v": cleaned})
    if not rows:
        raise ParseError(
            f'block "{metric} ({unit})": no data rows found.'
        )
    return rows


def validate_row(metric: str, unit: str, sub: str, rtype: str, v: list[str]) -> None:
    loc = f'block "{metric} ({unit})" row "{sub}" (type={rtype})'
    if rtype == "full":
        for i, cell in enumerate(v):
            if cell == SENTINEL or cell == "":
                raise ParseError(
                    f'{loc}: cell at col {i} ({STAGE_LABELS[i]}) is '
                    f'"{cell}"; full rows must have a value in every '
                    f"stage. Use type fp/gr0/gr1 to mark a missing stage."
                )
    elif rtype == "fp":
        for i in range(4):
            if v[i] != SENTINEL:
                raise ParseError(
                    f"{loc}: expected '-' in col {i} ({STAGE_LABELS[i]}); "
                    f'got "{v[i]}". fp rows must leave the 4 Floorplan '
                    f"columns as '-' (the merged note covers them)."
                )
        for i in range(4, 20):
            if v[i] in (SENTINEL, ""):
                raise ParseError(
                    f"{loc}: cell at col {i} ({STAGE_LABELS[i]}) is "
                    f'"{v[i]}"; fp rows must have values in the 16 '
                    f"non-Floorplan columns."
                )
    elif rtype in ("gr0", "gr1"):
        for i in range(16):
            if v[i] in (SENTINEL, ""):
                raise ParseError(
                    f"{loc}: cell at col {i} ({STAGE_LABELS[i]}) is "
                    f'"{v[i]}"; {rtype} rows must have values in the '
                    f"16 non-GlobalRoute columns."
                )
        for i in range(16, 20):
            if v[i] != SENTINEL:
                raise ParseError(
                    f"{loc}: expected '-' in col {i} ({STAGE_LABELS[i]}); "
                    f'got "{v[i]}". {rtype} rows must leave the 4 '
                    f"Global-route columns as '-' (the merged note covers them)."
                )
    else:
        raise ParseError(
            f'{loc}: unknown type "{rtype}"; valid types are '
            "full / fp / gr0 / gr1."
        )


def derive_and_validate_fp(metric: str, rows: list[dict]) -> bool:
    types = {r["type"] for r in rows}
    has_fp = "fp" in types
    if has_fp and types != {"fp"}:
        raise ParseError(
            f'block "{metric}": mixes type "fp" with {sorted(types - {"fp"})}. '
            "If any row is fp the whole block must be fp (the include "
            "template merges the Floorplan cell with rowspan = nrows)."
        )
    return has_fp


def validate_gr_pairing(metric: str, rows: list[dict]) -> None:
    for i, r in enumerate(rows):
        if r["type"] == "gr0":
            nxt = rows[i + 1] if i + 1 < len(rows) else None
            if not nxt or nxt["type"] != "gr1":
                raise ParseError(
                    f'block "{metric}" row "{r["sub"]}" (type=gr0): must '
                    'be immediately followed by a row with type "gr1". '
                    "The Global-route merged note uses rowspan=2 to span "
                    "the gr0 row and the next gr1 row."
                )
        elif r["type"] == "gr1":
            prv = rows[i - 1] if i > 0 else None
            if not prv or prv["type"] != "gr0":
                raise ParseError(
                    f'block "{metric}" row "{r["sub"]}" (type=gr1): must '
                    'be immediately preceded by a row with type "gr0".'
                )


def yaml_q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_yaml(meta: dict, blocks: list[dict]) -> str:
    out = io.StringIO()
    w = out.write
    w(HEADER_COMMENT)
    w("caption: " + yaml_q(meta["caption"]) + "\n")
    w("pdks: [" + ", ".join(meta["pdks"]) + "]\n")
    w("groups: [" + ", ".join(yaml_q(g) for g in meta["groups"]) + "]\n")
    w("fp_note: " + yaml_q(meta["fp_note"]) + "\n")
    w("gr_note: " + yaml_q(meta["gr_note"]) + "\n")
    w("blocks:\n")
    for b in blocks:
        w("  - metric: " + yaml_q(b["metric"]) + "\n")
        w("    unit: " + yaml_q(b["unit"]) + "\n")
        w("    fp: " + ("true" if b["fp"] else "false") + "\n")
        w("    rows:\n")
        for r in b["rows"]:
            expected_len = 20 if r["type"] == "full" else 16
            if len(r["v"]) != expected_len:
                raise ParseError(
                    f'block "{b["metric"]}" row "{r["sub"]}" '
                    f'(type={r["type"]}): emitter expected {expected_len} '
                    f"values after stripping sentinels, got {len(r['v'])}."
                )
            w("      - sub: " + yaml_q(r["sub"]) + "\n")
            w("        type: " + yaml_q(r["type"]) + "\n")
            w("        v: [" + ", ".join(yaml_q(v) for v in r["v"]) + "]\n")
    return out.getvalue()


def parse(md_text: str) -> tuple[dict, list[dict]]:
    meta, body = split_frontmatter(md_text)
    blocks = parse_blocks(body)
    if len(blocks) != 12:
        raise ParseError(
            f"content/table8.md: expected 12 metric blocks, found {len(blocks)}."
        )
    total_rows = sum(len(b["rows"]) for b in blocks)
    if total_rows != 46:
        raise ParseError(
            f"content/table8.md: expected 46 sub-rows total, found {total_rows}."
        )
    return meta, blocks


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true",
                   help="Parse and validate only; do not write.")
    p.add_argument("--output", default=str(YML_PATH),
                   help=f"Where to write the YAML (default: {YML_PATH}).")
    p.add_argument("--input", default=str(MD_PATH),
                   help=f"Markdown source (default: {MD_PATH}).")
    args = p.parse_args(argv)

    md_path = Path(args.input)
    if not md_path.is_file():
        print(f"error: markdown source not found: {md_path}", file=sys.stderr)
        return 2
    try:
        meta, blocks = parse(md_path.read_text(encoding="utf-8"))
        yml = emit_yaml(meta, blocks)
    except ParseError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    if args.check:
        print(f"ok: {md_path} parses cleanly "
              f"({len(blocks)} blocks, {sum(len(b['rows']) for b in blocks)} rows)")
        return 0

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(yml, encoding="utf-8")
    print(f"wrote {out}  blocks={len(blocks)} rows={sum(len(b['rows']) for b in blocks)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
